"""Taxon-clustered sensitivity, rare-taxon retrieval, and calibration audits.
Uses the verified 10 Bayesian extension OOF artifacts and archived baseline.
No claim of independent folds; sign flips are at the taxon level (8 clusters).
"""
from pathlib import Path
import itertools
import numpy as np
import pandas as pd

files=sorted(Path("downloaded").rglob("*_oof.csv"))
assert len(files)==10, len(files)
ext=pd.concat([pd.read_csv(p) for p in files],ignore_index=True)
base=pd.read_csv("results/bayes_spatial_cv_predictions.csv")
base=base.rename(columns={"mean_probability":"probability"})
base["variant"]="baseline"
cols=["id","plot","species","fold","observed","probability","variant"]
df=pd.concat([base[cols],ext[cols]],ignore_index=True)
assert set(df.variant)=={"baseline","quadratic","no_pool"}
assert df.groupby("variant").size().eq(9336).all()
assert not df.duplicated(["variant","id"]).any()
ref=base[["id","plot","species","fold","observed"]].sort_values("id").reset_index(drop=True)
for variant,g in df.groupby("variant"):
    assert g[["id","plot","species","fold","observed"]].sort_values("id").reset_index(drop=True).equals(ref)
out=Path("results/bayes_extensions")
out.mkdir(parents=True,exist_ok=True)
# Existing paired metrics are regenerated by the preceding script.
m=pd.read_csv(out/"paired_baseline_differences.csv")
metrics=["auc","ap","brier","logloss"]
rng=np.random.default_rng(20261103)
rows=[]
for variant,g in m.groupby("variant"):
    for metric in metrics:
        key="delta_"+metric
        # Each taxon contributes one equal-weight mean over its eligible folds.
        per=g.groupby("species")[key].mean().dropna()
        vals=per.to_numpy()
        assert len(vals)>=3
        observed=float(vals.mean())
        boots=np.mean(rng.choice(vals,size=(20000,len(vals)),replace=True),axis=1)
        flips=np.array([np.mean(vals*np.array(sign)) for sign in itertools.product((-1,1),repeat=len(vals))])
        p=float(np.mean(np.abs(flips)>=abs(observed)-1e-14))
        rows.append(dict(variant=variant,metric=metric,n_taxa=len(vals),
                         equal_taxon_mean_delta=observed,
                         bootstrap_ci_low=float(np.quantile(boots,.025)),
                         bootstrap_ci_high=float(np.quantile(boots,.975)),
                         exploratory_exact_signflip_p=p))
pd.DataFrame(rows).to_csv(out/"taxon_clustered_sensitivity.csv",index=False)
# Rare species retrieval: 25 highest probability plots within each held-out fold.
rare=["nsw19","nsw20","nsw22"]
ret=[]
for (variant,species,fold),g in df[df.species.isin(rare)].groupby(["variant","species","fold"]):
    g=g.sort_values(["probability","id"],ascending=[False,True])
    assert len(g)>=25
    hits=int(g.head(25).observed.sum())
    ret.append(dict(variant=variant,species=species,fold=int(fold),k=25,
                    n=len(g),positives=int(g.observed.sum()),hits=hits,
                    random_expected_hits=25*float(g.observed.mean())))
retr=pd.DataFrame(ret)
retr.to_csv(out/"rare_taxon_top25_by_fold.csv",index=False)
retr.groupby(["variant","species"],as_index=False).agg(
    hits=("hits","sum"),positives=("positives","sum"),
    random_expected_hits=("random_expected_hits","sum")
).to_csv(out/"rare_taxon_top25_summary.csv",index=False)
# Reliability by fixed probability bins and proper scores.
cal=df.assign(bin=pd.cut(df.probability,bins=[0,.01,.025,.05,.1,.2,.4,.6,.8,1.000001],
                        include_lowest=True))
cal.groupby(["variant","bin"],observed=False).agg(
    n=("observed","size"),mean_predicted=("probability","mean"),
    observed_rate=("observed","mean")
).reset_index().to_csv(out/"reliability_bins.csv",index=False)
with open(out/"ROBUSTNESS_SUMMARY.md","w") as f:
    f.write("# Bayesian extension robustness audit\n\n")
    f.write("Taxon is the resampling/sign-flip unit; 8 taxa maximum. These are exploratory sensitivity analyses, not confirmatory tests. The 5 spatial folds for each taxon are correlated.\n\n")
    f.write(pd.DataFrame(rows).to_markdown(index=False,floatfmt=".6f"))
    f.write("\n\nRare-taxon top-25 hits (sum across five held-out folds):\n\n")
    f.write(retr.groupby(["variant","species"],as_index=False).agg(hits=("hits","sum")).to_markdown(index=False))
    f.write("\n")
print(pd.DataFrame(rows).to_string(index=False))
print(retr.groupby(["variant","species"]).hits.sum().to_string())
